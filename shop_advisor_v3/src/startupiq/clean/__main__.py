"""Rebuild all cleaned tables from raw: python -m startupiq.clean [rossmann uci olist signals]

Writes data/processed/*.parquet, a JSON log per dataset, and docs/results/cleaning_log.md.
"""

from __future__ import annotations

import sys
import time
from pathlib import Path

from startupiq.clean import olist, rossmann, signals, uci_retail

CLEANERS = {"rossmann": rossmann.run, "uci": uci_retail.run, "olist": olist.run, "signals": signals.run}
REPORT = Path("docs/results/cleaning_log.md")


def main(argv: list[str]) -> int:
    names = argv or list(CLEANERS)
    sections = []
    for name in names:
        t = time.time()
        log = CLEANERS[name]()
        print(f"{name}: {len(log.entries)} rules, {time.time() - t:.0f}s")
        sections.append(log.to_markdown())
    if not argv:  # only a full rebuild rewrites the combined report
        REPORT.parent.mkdir(parents=True, exist_ok=True)
        REPORT.write_text("# Cleaning log\n\nGenerated by `python -m startupiq.clean`. Do not edit by hand.\n\n" + "\n".join(sections), encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
