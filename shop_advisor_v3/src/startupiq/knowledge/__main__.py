"""Draw the knowledge model (Task 1 deliverable): python -m startupiq.knowledge

Writes docs/results/figures/16_knowledge_frames.png (frame hierarchy) and
17_knowledge_moves.png (moves -> metrics they affect and constraints they require),
plus docs/results/knowledge.md listing every frame, slot and relation.
"""

from __future__ import annotations

from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import networkx as nx  # noqa: E402

from startupiq.knowledge.constraints import CONSTRAINTS  # noqa: E402
from startupiq.knowledge.kb import METRICS, KnowledgeBase  # noqa: E402
from startupiq.knowledge.ontology import move_names  # noqa: E402

FIG = Path("docs/results/figures")
SERIES = ["#2a78d6", "#eb6834", "#1baf7a", "#eda100"]
SURFACE, INK, INK2, GRID = "#fcfcfb", "#0b0b0b", "#52514e", "#c9c8c3"


def _tree_layout(g: nx.DiGraph, root: str, narrow: frozenset = frozenset()) -> dict:
    """Top-down tree: children (who point at the parent with is_a) below it."""
    kids = {n: sorted(u for u, v in g.edges if v == n) for n in g.nodes}
    pos, x = {}, [0]

    def place(n, depth):
        if not kids[n]:
            pos[n] = (x[0], -depth); x[0] += 1 if n in narrow else 2.4  # entity frames need room for slot names
            return pos[n][0]
        xs = [place(k, depth + 1) for k in kids[n]]
        pos[n] = (sum(xs) / len(xs), -depth)
        return pos[n][0]
    place(root, 0)
    return pos


def frames_figure(kb: KnowledgeBase) -> None:
    g = nx.DiGraph([(u, v) for u, v, d in kb.net.edges(data=True) if d["label"] == "is_a"])
    moves = frozenset(move_names(kb.classes))
    pos = _tree_layout(g, "Thing", moves)
    fig, ax = plt.subplots(figsize=(15, 6.2), facecolor=SURFACE)
    nx.draw_networkx_edges(g, pos, ax=ax, edge_color=GRID, arrows=False, width=1.2)
    colors = [SERIES[1] if n in moves else SERIES[0] for n in g.nodes]
    nx.draw_networkx_nodes(g, pos, ax=ax, node_color=colors, node_size=260, edgecolors=SURFACE, linewidths=2)
    for n, (x, y) in pos.items():
        slots = [s for s in kb.classes[n].slots if kb.classes[n].slots[s].value is None or n not in moves][:4]
        label = n if n in moves or not slots else n + "\n" + "\n".join(slots)
        ax.text(x, y - 0.18, label, ha="center", va="top", fontsize=7.5 if n in moves else 8, color=INK, rotation=0 if n not in moves else 35)
    ax.set_title("Frame hierarchy (is_a). Blue: entity frames with their own slots; orange: move frames from configs/moves.yaml",
                 loc="left", fontsize=10, color=INK)
    ax.axis("off"); ax.set_ylim(min(y for _, y in pos.values()) - 1.9, 0.4)
    FIG.mkdir(parents=True, exist_ok=True)
    fig.tight_layout(); fig.savefig(FIG / "16_knowledge_frames.png", dpi=110, facecolor=SURFACE); plt.close(fig)


def moves_figure(kb: KnowledgeBase) -> None:
    moves = move_names(kb.classes)
    cons = list(CONSTRAINTS)
    metrics = [m for m in METRICS if any(d["label"] == "affects" for _, _, d in kb.net.in_edges(m, data=True))]
    pos = {m: (0, -i) for i, m in enumerate(moves)}
    pos.update({m: (-1.6, -i * (len(moves) - 1) / max(1, len(metrics) - 1)) for i, m in enumerate(metrics)})
    pos.update({c: (1.6, -i * (len(moves) - 1) / max(1, len(cons) - 1)) for i, c in enumerate(cons)})
    fig, ax = plt.subplots(figsize=(12, 6.2), facecolor=SURFACE)
    for u, v, d in kb.net.edges(data=True):
        if d["label"] == "affects" and v in pos:
            color = SERIES[2] if d.get("sign") == "+" else SERIES[1]
            ax.annotate("", xy=pos[v], xytext=pos[u], arrowprops=dict(arrowstyle="-|>", color=color, lw=1, alpha=0.8, shrinkA=8, shrinkB=8))
        if d["label"] == "requires" and v in pos:
            ax.annotate("", xy=pos[v], xytext=pos[u], arrowprops=dict(arrowstyle="-|>", color=INK2, lw=0.9, ls="--", alpha=0.7, shrinkA=8, shrinkB=8))
    for group, color, align, dx in ((moves, SERIES[0], "center", 0), (metrics, SERIES[2], "right", -0.08), (cons, INK2, "left", 0.08)):
        for n in group:
            x, y = pos[n]
            ax.scatter([x], [y], s=110, color=color, edgecolors=SURFACE, linewidths=2, zorder=3)
            ax.text(x + dx, y + (0.32 if align == "center" else 0), n.replace("_", " "), ha=align, va="center", fontsize=8.5, color=INK)
    ax.set_title("Semantic network: moves (middle) affect metrics (left; green +, orange -) and require constraints (right, dashed)",
                 loc="left", fontsize=10, color=INK)
    ax.axis("off")
    fig.tight_layout(); fig.savefig(FIG / "17_knowledge_moves.png", dpi=110, facecolor=SURFACE); plt.close(fig)


def listing(kb: KnowledgeBase) -> None:
    lines = ["# Knowledge model (Task 1)", "", "Generated by `python -m startupiq.knowledge`. Do not edit by hand.", "",
             "![frames](figures/16_knowledge_frames.png)", "", "![moves](figures/17_knowledge_moves.png)", "", "## Class frames", "",
             "| Frame | is_a | Own slots (default / range / if-needed) |", "| --- | --- | --- |"]
    for name, f in kb.classes.items():
        slots = []
        for s, slot in f.slots.items():
            bits = [x for x in (f"default {slot.default!r}" if slot.default is not None else "",
                                f"range {slot.range}" if slot.range is not None else "",
                                "if-needed" if slot.if_needed else "", f"= {slot.value!r}" if slot.value is not None and not isinstance(slot.value, (dict, list)) else "") if x]
            slots.append(f"{s} ({'; '.join(bits)})" if bits else s)
        lines.append(f"| {name} | {f.parent.name if f.parent else '-'} | {', '.join(slots) or '-'} |")
    lines += ["", "## Constraints", "", "| Name | Statement |", "| --- | --- |"]
    lines += [f"| {c.name} | {c.statement} |" for c in CONSTRAINTS.values()]
    lines += ["", f"Semantic network: {kb.net.number_of_nodes()} nodes, {kb.net.number_of_edges()} edges "
                  f"({', '.join(sorted({d['label'] for _, _, d in kb.net.edges(data=True)}))})."]
    Path("docs/results/knowledge.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> int:
    kb = KnowledgeBase()
    frames_figure(kb); moves_figure(kb); listing(kb)
    print("wrote docs/results/knowledge.md and 2 figures")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
